public class PrintEssay {
    public static void main(String[] args) {
        // 第一部分：开头（2句）
        String[] opening = {
            "青春是一张素白的宣纸，等待着色彩的晕染。",           // 以绘画比喻青春的空白与可塑性
            "而我选择用《平凡的世界》这本厚重的书，在那最好的年华里，一笔一画描摹出独属于我的斑斓图景。" // 点明“读书”为青春着色的核心意象
        };

        // 第二部分：小标题一 —— 初遇，黄土情深
        String[] part1 = {
            "## 初遇，黄土情深",                                    // 小标题：初次邂逅，奠定黄土高原的情感基调
            "十六岁的夏天，我在旧书摊上与《平凡的世界》初次相遇。", // 交代时间、地点与书籍的缘分
            "泛黄的封面上，一个农民的背影正走向无垠的黄土高原。",   // 封面细节，引入“黄土”与“平凡”的象征
            "翻开书页，扑面而来的不是墨香，而是一种粗粝的、带着尘土气息的辽阔。", // 感官描写，突出书的厚重与真实
            "“一九七五年二三月间，一个平平常常的日子，细濛濛的雨丝夹着一星半点的雪花……”路遥的文字像陕北的信天游，苍凉中藏着滚烫的温度。", // 引用原文，比喻文字风格
            "我跟着孙少平走进县高中的食堂，看他躲在角落里啃着最便宜的黑面馍，心里竟涌起一种奇异的共鸣——原来苦难也可以被讲述得如此庄重。", // 共情少平，领悟苦难的庄严
            "那天下午，窗外的梧桐叶落了满地，而我坐在窗前一动不动，任凭那片黄土地上的风沙吹进十六岁的胸膛。", // 环境烘托，内心被书中的世界强烈冲击
            "那一刻我知道，青春的画布上，从此多了一抹沉郁而温暖的土黄。" // 呼应开头比喻，具象化第一层青春底色
        };

        // 第三部分：小标题二 —— 再品，命运如歌
        String[] part2 = {
            "## 再品，命运如歌",                                    // 小标题：重读时感悟到命运的起伏与旋律
            "十七岁的寒假，我第二次捧起这本书，在炉火旁读到了孙少平离开双水村去黄原城揽工的情节。", // 时间推移，聚焦少平进城务工的转折
            "那些深夜，他借着工棚里昏暗的灯光读书，脊背上是被石头磨出的血痂，眼睛里却映着《牛虻》与《约翰·克利斯朵夫》的光芒。", // 少平在苦难中坚持阅读，与“我”形成镜像
            "我忽然在这两个平行的世界里看见了自己的影子——我们都在各自的“黄原”里挣扎，都在用读书对抗着生活的平庸。", // 自我投射，点明读书对抗平庸的主题
            "而孙少安在砖窑倒塌后蹲在河滩上痛哭的那一夜，炉火映在我脸上，我分明感到有什么滚烫的东西正从眼角滑落。", // 少安的失败引发共鸣，泪水是理解的证明
            "原来所谓命运，就是一次次的跌倒与爬起；所谓青春，就是在最深的夜里依然相信天亮。", // 提炼哲理，升华对命运和青春的认识
            "那些人物像远方的亲人，他们流汗、流泪、流血，却始终没有松开握紧命运的手。", // 将书中人物视为亲人，强调他们的坚韧
            "而我在他们的故事里，学会了如何握紧自己的。" // 读书的收获：从他人命运中汲取力量
        };

        // 第四部分：小标题三 —— 重翻，平凡铸光
        String[] part3 = {
            "## 重翻，平凡铸光",                                    // 小标题：第三次阅读，领悟平凡之中生出光芒
            "十八岁的春天，高考前夕，我再次翻开这本被翻得卷边的书。", // 时间推进至高考前，书籍已被翻旧
            "这一次，我看见了以前不曾看见的东西——田晓霞在洪水中牺牲后，孙少平独自走上古塔山，在杜梨树下翻开她留下的三本日记，那句“不要见怪，不要见外”让整个春天都静默了。", // 发现晓霞之死与少平的悲伤，细节打动人心
            "可生活还在继续，他回到大牙湾煤矿，下井，采煤，在那片黑暗的地心深处寻找光明。", // 少平回归日常，隐喻在黑暗中坚持
            "重读至此，我忽然懂得——平凡不是平庸，而是在认清生活的真相之后，依然热爱生活。", // 核心感悟：平凡即英雄主义
            "那些曾经让我泪流满面的苦难，如今读来却成了一种庄严的祝福。", // 对苦难的理解加深，化为祝福
            "高考前夕的焦虑在这重读中渐渐沉淀，我明白了，人生的考场从不只在六月，而在每一个需要选择挺立的瞬间。", // 将书中精神应用于现实，升华自我
            "那本翻旧的书，像一面镜子，照见了三年来悄然长大的自己。" // 书如镜，映照成长
        };

        // 第五部分：结尾（3句）
        String[] ending = {
            "如今，那本《平凡的世界》还立在书桌最顺手的位置，书页间夹着三年来落下的银杏叶、梧桐叶和一片不知名的花瓣。", // 书籍成为青春的实物印记
            "读书给予我的，不只是一个故事，而是一种在平凡中仰望星空的勇气。", // 总结读书的本质：勇气
            "当路遥的文字渗入血脉，青春便不再惧怕黯淡——因为在那些黄土般质朴的字句里，我早已看见，最平凡的生命，也能活成一道光。" // 结尾点题，呼应“平凡铸光”
        };

        // 分三次打印
        // 第一次：打印开头
        for (String s : opening) {
            System.out.println(s);
        }

        // 第二次：依次打印三个小标题部分（每个部分连续输出）
        for (String s : part1) {
            System.out.println(s);
        }
        for (String s : part2) {
            System.out.println(s);
        }
        for (String s : part3) {
            System.out.println(s);
        }

        // 第三次：打印结尾
        for (String s : ending) {
            System.out.println(s);
        }
    }
}
